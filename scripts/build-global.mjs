// Builds resources/dist/payments-core.global.js (plain <script>, exposes window.PaymentsCore)
// from the ES module, so Blade/Livewire apps need no bundler:  node scripts/build-global.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../resources/js/core/payments-core.js', import.meta.url), 'utf8');
const body = src.replace(/^export /gm, '');
const out = `/* laravel-payments core (generated by scripts/build-global.mjs: do not edit) */
(function (global) {
${body}
  global.PaymentsCore = { STEPS: STEPS, createPaymentFlow: createPaymentFlow };
})(typeof window !== 'undefined' ? window : globalThis);
`;

writeFileSync(new URL('../resources/dist/payments-core.global.js', import.meta.url), out);
console.log('built resources/dist/payments-core.global.js');
